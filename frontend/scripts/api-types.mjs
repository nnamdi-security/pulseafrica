/* Generates src/lib/api/schema.d.ts from FastAPI's OpenAPI schema (decision 0016).

     pnpm api:types    regenerate after any backend schema change, and commit the result
     pnpm api:check    fail if the committed file is out of date (CI)

   The schema comes from `python -m app.export_openapi` in backend/, which needs no server
   or database. The Python used is $PYTHON, else backend/.venv's, else python3. */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const backend = join(root, '..', 'backend');
const target = join(root, 'src', 'lib', 'api', 'schema.d.ts');
const venvPython = join(backend, '.venv', 'bin', 'python');
const python = process.env.PYTHON || (existsSync(venvPython) ? venvPython : 'python3');

const schema = JSON.parse(
  execFileSync(python, ['-m', 'app.export_openapi'], { cwd: backend, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 }),
);
const header =
  '/* Generated by `pnpm api:types` from FastAPI\'s OpenAPI schema. Do not edit by hand. */\n\n';
const output = header + astToString(await openapiTS(schema));

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== output) {
    console.error('src/lib/api/schema.d.ts is out of date with the API. Run `pnpm api:types` and commit it.');
    process.exit(1);
  }
  console.log('API types are up to date.');
} else {
  writeFileSync(target, output);
  console.log(`Wrote ${target}`);
}
